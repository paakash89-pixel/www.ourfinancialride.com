const prettyName = (ticker: string): string => {
  if (NAME_MAP[ticker]) return NAME_MAP[ticker];
  return ticker.replace(/[._-]/g, " ");
};

const buildRegionEntries = (
  tickers: readonly string[],
  region: Region
): CompanyEntry[] =>
  tickers.map((ticker) => ({
    ticker,
    name: prettyName(ticker),
    region
  }));

const dedupe = (items: CompanyEntry[]): CompanyEntry[] => {
  const seen = new Set<string>();
  const output: CompanyEntry[] = [];

  for (const item of items) {
    const key = `${item.region}:${item.ticker}`;
    if (seen.has(key)) continue;
    seen.add(key);
    output.push(item);
  }

  return output;
};

export const COMPANY_UNIVERSE: CompanyEntry[] = dedupe([
  ...buildRegionEntries(US_TICKERS, "US"),
  ...buildRegionEntries(IN_TICKERS, "IN")
]);
